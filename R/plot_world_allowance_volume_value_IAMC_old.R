script <- sub('^--file=','',grep('^--file=',commandArgs(FALSE),value=TRUE))
root <- dirname(dirname(normalizePath(script)));out <- file.path(root,'output')
d <- read.csv(file.path(out,'world_allowance_trade_IAMC_old_source.csv'))
years <- seq(2025,2100,5)
get <- function(r,v)d$value[match(paste(r,years,v),paste(d$region,d$year,d$variable))]
q <- get('World','Trd_Emi_All_Vol');money <- get('World','Trd_Emi_All_Val')
stopifnot(all(is.finite(q)),all(is.finite(money)))
regions <- setdiff(unique(d$region),'World')
sumside <- function(v,positive=TRUE)sapply(years,function(y){z <- d$value[d$year==y & d$variable==v & d$region %in% regions];sum(if(positive)pmax(z,0) else pmax(-z,0))})
audit <- data.frame(year=years,World_volume=q,regional_imports=sumside('Trd_Emi_All_Vol'),regional_exports=sumside('Trd_Emi_All_Vol',FALSE),World_value=money,regional_purchase_value=sumside('Trd_Emi_All_Val'),regional_sale_value=sumside('Trd_Emi_All_Val',FALSE))
stopifnot(max(abs(q-audit$regional_imports))<1e-7,max(abs(q-audit$regional_exports))<1e-7)
audit$World_value_minus_regional_purchase_sum <- money-audit$regional_purchase_value
result <- data.frame(year=years,trade_volume_GtCO2eq_per_year=q/1000,trade_value_billion_USD2010_per_year=money)
write.csv(result,file.path(out,'world_allowance_volume_value_IAMC_old.csv'),row.names=FALSE)
write.csv(audit,file.path(out,'world_allowance_volume_value_IAMC_old_audit.csv'),row.names=FALSE)
draw <- function(){
 par(mar=c(8,5.2,4.3,5.5),family='sans',mgp=c(3,.7,0),las=1)
 yl <- c(0,ceiling(max(q/1000)*1.13));yr <- c(0,ceiling(max(money)*1.13/100)*100)
 plot(years,q/1000,type='n',xlim=c(2026,2100),ylim=yl,xaxs='i',yaxs='i',axes=FALSE,xlab='Year',ylab='')
 abline(h=pretty(yl),col='#EEEEEE');abline(v=2050,lty=3,col='#AAAAAA')
 lines(years,q/1000,col='#1457ED',lwd=2.3);points(years,q/1000,col='#1457ED',pch=19,cex=.7)
 axis(1,at=c(2026,2030,2040,2050,2060,2075,2090,2100));axis(2,col.axis='#1457ED')
 mtext('Trade volume (Gt CO2-equivalent / year)',2,line=3.1,las=0,col='#1457ED')
 par(new=TRUE)
 plot(years,money,type='n',xlim=c(2026,2100),ylim=yr,xaxs='i',yaxs='i',axes=FALSE,xlab='',ylab='')
 lines(years,money,col='#F04416',lwd=2.3,lty=2);points(years,money,col='#F04416',pch=17,cex=.7)
 axis(4,col.axis='#F04416');mtext('Trade value (billion 2010 USD / year)',4,line=3.2,las=0,col='#F04416');box(col='#AAAAAA')
 mtext('Global emissions allowance trade: volume and value',3,line=2.1,adj=0,font=2,cex=1.25)
 mtext('NZE_w/ET | Previous model results | IAMC World series | Annual flows',3,line=.7,adj=0,cex=.88,col='#465261')
 par(fig=c(0,1,0,.12),new=TRUE,mar=rep(0,4));plot.new()
 legend('top',legend=c('Trade volume (left axis)','Trade value (right axis)'),col=c('#1457ED','#F04416'),lty=c(1,2),pch=c(19,17),lwd=2,horiz=TRUE,bty='n',cex=.95)
 text(.5,.18,'Source: IAMC World Trd_Emi_All_Vol and Trd_Emi_All_Val. Markers: five-year observations; lines connect observations.',cex=.74,col='#465261')
}
stem <- file.path(out,'world_allowance_volume_value_IAMC_old')
png(paste0(stem,'.png'),width=2600,height=1450,res=180);draw();dev.off()
pdf(paste0(stem,'.pdf'),width=14.444,height=8.056);draw();dev.off()
